package dev.fmangoni.forge.tour.show;

import com.fasterxml.jackson.core.JsonProcessingException;
import dev.fmangoni.forge.json.Json;
import dev.fmangoni.forge.report.shell.Html;
import dev.fmangoni.forge.tour.model.Tour;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import lombok.experimental.UtilityClass;

/**
 * The tour as a page that plays itself.
 *
 * <p>One file, opened by double-clicking it: the code on the left, the line being talked about lit
 * up, the sentence being said underneath, and the browser's own voice reading it. No server, no
 * build and nothing to install, which is the same reason the reports are files rather than a site.
 *
 * <p>The scenes are embedded as data rather than rendered into markup, because the page is a player
 * — it needs to jump to a chapter, step back a line and follow along with a recording, and all
 * three are easy with the tour in hand and awkward with it baked into HTML.
 */
@UtilityClass
public class TourPage {

    public void write(Tour tour, Path file) throws IOException {
        Files.createDirectories(file.getParent());
        Files.writeString(file, render(tour), StandardCharsets.UTF_8);
    }

    public String render(Tour tour) {
        return Html.page(tour.title() + " — code tour", BODY
                .replace("__TITLE__", Html.escape(tour.title()))
                .replace("__SUBTITLE__", Html.escape(tour.subtitle()))
                .replace("__DATA__", data(tour)))
                .replace("</head>", "<style>" + CSS + "</style></head>");
    }

    /**
     * The tour as JSON inside the page.
     *
     * <p>{@code </script>} is the one sequence that can end the block early, and source code is
     * exactly the kind of text that contains it. Splitting the slash is the standard answer and
     * leaves the string identical once parsed.
     */
    private String data(Tour tour) {
        try {
            return Json.mapper().writeValueAsString(tour).replace("</", "<\\/");
        } catch (JsonProcessingException e) {
            return "{\"title\":\"\",\"subtitle\":\"\",\"chapters\":[]}";
        }
    }

    private final String CSS = """
            .tour { display: grid; grid-template-columns: 15rem 1fr; gap: 1rem; align-items: start; }
            @media (max-width: 52rem) { .tour { grid-template-columns: 1fr; } }
            .chapters { max-height: 34rem; overflow-y: auto; border: 1px solid var(--line);
                        border-radius: .5rem; background: var(--card); padding: .35rem; }
            .chapters button { display: block; width: 100%; text-align: left; border: 0;
                        background: none; color: inherit; font: inherit; font-size: .85rem;
                        padding: .3rem .45rem; border-radius: .3rem; cursor: pointer; }
            .chapters button:hover { background: var(--bg); }
            .chapters button.on { background: var(--bg); font-weight: 600; }
            .chapters .mod { margin-top: .5rem; text-transform: uppercase; letter-spacing: .04em;
                        font-size: .7rem; color: var(--muted); }
            .stage { border: 1px solid var(--line); border-radius: .5rem; background: var(--card);
                        padding: 1rem 1.15rem; }
            .stage h2 { margin: 0; font-size: 1.05rem; }
            .where { color: var(--muted); font-size: .8rem; margin: .1rem 0 .7rem; }
            .code { margin: 0; max-height: 26rem; overflow: auto; }
            .code .row { display: flex; gap: .75rem; padding: 0 .3rem; border-radius: .2rem; }
            .code .no { color: var(--muted); text-align: right; min-width: 2.5rem;
                        user-select: none; font-variant-numeric: tabular-nums; }
            .code .lit { background: rgba(250, 204, 21, .18); outline: 1px solid rgba(250, 204, 21, .5); }
            .said { margin: .8rem 0 0; padding: .7rem .85rem; border-left: 3px solid var(--wait);
                        background: var(--bg); border-radius: .3rem; font-size: .95rem; }
            .bar { display: flex; gap: .5rem; align-items: center; margin-top: .9rem; flex-wrap: wrap; }
            .bar button { padding: .4rem .8rem; border: 1px solid var(--line); border-radius: .35rem;
                        background: var(--card); color: inherit; font: inherit; cursor: pointer; }
            .bar button:hover { border-color: var(--fg); }
            .bar .count { color: var(--muted); font-size: .85rem; margin-left: auto; }
            .track { height: 3px; background: var(--line); border-radius: 2px; margin-top: .6rem; }
            .track div { height: 3px; background: var(--wait); border-radius: 2px; width: 0; }
            """;

    private final String BODY = """
            <h1>__TITLE__</h1>
            <p class="sub">A narrated tour: __SUBTITLE__. Nothing here was generated by a model —
            every sentence comes from the code and the notes beside it.</p>
            <div class="tour">
              <nav class="chapters" id="chapters"></nav>
              <section class="stage">
                <h2 id="heading"></h2>
                <p class="where" id="where"></p>
                <pre class="code" id="code"></pre>
                <p class="said" id="said"></p>
                <div class="bar">
                  <button id="play">Play</button>
                  <button id="back">Back</button>
                  <button id="next">Next</button>
                  <span class="count" id="count"></span>
                </div>
                <div class="track"><div id="progress"></div></div>
              </section>
            </div>
            <script id="tour" type="application/json">__DATA__</script>
            <script>
            const tour = JSON.parse(document.getElementById("tour").textContent);
            const scenes = [];
            tour.chapters.forEach((chapter, index) => {
              chapter.scenes.forEach(scene => scenes.push({...scene, chapter: index, name: chapter.title}));
            });

            let at = 0;
            let playing = false;

            /* The chapter list doubles as the table of contents: module headings are the chapters
               with nothing on screen, which is what makes them headings rather than entries. */
            function chapters() {
              const nav = document.getElementById("chapters");
              tour.chapters.forEach((chapter, index) => {
                const first = scenes.findIndex(scene => scene.chapter === index);
                if (first < 0) return;
                const button = document.createElement("button");
                const heading = !chapter.scenes[0].code.lines.length;
                button.textContent = chapter.title;
                button.className = heading ? "mod" : "";
                button.dataset.scene = first;
                button.onclick = () => { show(first); if (playing) say(); };
                nav.appendChild(button);
              });
            }

            function show(index) {
              at = Math.max(0, Math.min(scenes.length - 1, index));
              const scene = scenes[at];
              document.getElementById("heading").textContent = scene.title;
              document.getElementById("where").textContent = scene.code.file || tour.subtitle;
              document.getElementById("said").textContent = scene.said;
              document.getElementById("count").textContent = (at + 1) + " of " + scenes.length;
              document.getElementById("progress").style.width =
                ((at + 1) / scenes.length * 100) + "%";
              code(scene.code);
              mark(scene.chapter);
            }

            function code(view) {
              const box = document.getElementById("code");
              box.textContent = "";
              let lit = null;
              view.lines.forEach((line, offset) => {
                const number = view.firstLine + offset;
                const row = document.createElement("div");
                row.className = "row" + (number >= view.litFrom && number <= view.litTo ? " lit" : "");
                const no = document.createElement("span");
                no.className = "no";
                no.textContent = number;
                const text = document.createElement("span");
                text.textContent = line;
                row.append(no, text);
                box.appendChild(row);
                if (row.className.includes("lit") && !lit) lit = row;
              });
              if (lit) lit.scrollIntoView({block: "center", behavior: "smooth"});
            }

            function mark(chapter) {
              document.querySelectorAll("#chapters button").forEach(button => {
                const scene = scenes[Number(button.dataset.scene)];
                button.classList.toggle("on", scene && scene.chapter === chapter);
              });
            }

            /*
             * The best voice this browser has, rather than whichever one it defaults to.
             *
             * The default is usually the oldest voice installed, and the gap between that and a
             * natural one is the difference between listening to an hour of this and not. Edge
             * supplies natural voices that Chrome does not, so the same page sounds markedly
             * better in one than the other and neither needs anything installed.
             */
            function bestVoice() {
              if (typeof speechSynthesis.getVoices !== "function") return null;
              const voices = speechSynthesis.getVoices().filter(v => (v.lang || "").startsWith("en"));
              const wanted = ["Natural", "Online", "(HD)", "Aria", "Ava", "Jenny", "Guy", "Emma", "Mark"];
              for (const name of wanted) {
                const found = voices.find(v => v.name && v.name.includes(name));
                if (found) return found;
              }
              return null;
            }

            /* The voice is the browser's. A machine with none still shows every word, which is the
               same trade the dashboard makes: the text is the tour, the speech is how it is played. */
            function say() {
              if (!window.speechSynthesis) return;
              speechSynthesis.cancel();
              const utterance = new SpeechSynthesisUtterance(scenes[at].said);
              const voice = bestVoice();
              if (voice) utterance.voice = voice;
              utterance.rate = 0.95;
              utterance.onend = () => {
                if (!playing) return;
                if (at < scenes.length - 1) { show(at + 1); say(); } else { stop(); }
              };
              speechSynthesis.speak(utterance);
            }

            function stop() {
              playing = false;
              document.getElementById("play").textContent = "Play";
              if (window.speechSynthesis) speechSynthesis.cancel();
            }

            document.getElementById("play").onclick = () => {
              if (playing) { stop(); return; }
              playing = true;
              document.getElementById("play").textContent = "Pause";
              say();
            };
            document.getElementById("back").onclick = () => { show(at - 1); if (playing) say(); };
            document.getElementById("next").onclick = () => { show(at + 1); if (playing) say(); };
            document.addEventListener("keydown", event => {
              if (event.key === "ArrowRight") { show(at + 1); if (playing) say(); }
              if (event.key === "ArrowLeft") { show(at - 1); if (playing) say(); }
            });

            chapters();
            show(0);
            </script>
            """;
}
